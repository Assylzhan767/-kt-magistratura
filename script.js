  scoreQuestion(question, selected) {
    const correct = new Set(question.correctSet);
    const chosen = new Set(selected);

    const same = this.setsEqual(correct, chosen);
    if (!question.multiple) {
      return same ? 2 : 0;
    }
    if (same) return 2;

    const diff = this.symmetricDifferenceSize(correct, chosen);
    if (diff === 1) return 1;
    return 0;
  }

  setsEqual(a, b) {
    if (a.size !== b.size) return false;
    for (const x of a) if (!b.has(x)) return false;
    return true;
  }

  symmetricDifferenceSize(a, b) {
    let count = 0;
    for (const x of a) if (!b.has(x)) count += 1;
    for (const x of b) if (!a.has(x)) count += 1;
    return count;
  }

  finishExam(force = false) {
    if (!this.currentExam) return;
    this.stopTimer();

    const exam = this.currentExam;
    let totalPoints = 0;
    let maxPoints = 0;
    let correctCount = 0;
    const results = [];

    exam.questions.forEach((q, idx) => {
      const selected = exam.answers[idx];
      const points = this.scoreQuestion(q, selected);
      const isExact = this.setsEqual(new Set(q.correctSet), new Set(selected));
      totalPoints += points;
      maxPoints += 2;
      if (isExact) correctCount += 1;

      if (!isExact && !this.errors.some(e => e.id === q.id)) {
        this.errors.push({
          id: q.id,
          subject: q.subject,
          topic: q.topic,
          difficulty: q.difficulty,
          question: q.question,
          options: q.options,
          correct: q.correctSet.length === 1 ? q.correctSet[0] : q.correctSet,
          explanation: q.explanation,
          multiple: q.multiple,
          selected
        });
      }

      results.push({
        ...q,
        selected,
        points,
        correct: q.correctSet
      });
    });

    localStorage.setItem(STORAGE_KEYS.errors, JSON.stringify(this.errors));
    this.renderErrors();

    const percent = Math.round((totalPoints / maxPoints) * 100);
    const record = {
      date: new Date().toLocaleDateString('ru-RU'),
      mode: exam.title,
      score: `${totalPoints}/${maxPoints}`,
      exact: `${correctCount}/${exam.questions.length}`,
      percent,
      time: this.formatElapsed(exam.elapsedSeconds)
    };
    this.history.unshift(record);
    localStorage.setItem(STORAGE_KEYS.history, JSON.stringify(this.history));

    this.currentExam = {
      ...exam,
      results
    };
    this.renderResults(totalPoints, maxPoints, percent, correctCount);
    this.renderHistory();
    this.showView('results', false);
  }

