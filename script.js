  ensureQueue(poolIds, key, count) {
    let queue = JSON.parse(localStorage.getItem(key) || '[]');
    const poolSet = new Set(poolIds);
    queue = queue.filter(id => poolSet.has(id));

    while (queue.length < count) {
      const used = new Set(queue);
      const missing = poolIds.filter(id => !used.has(id));
      const batch = missing.length ? this.shuffle(missing) : this.shuffle(poolIds);
      queue = queue.concat(batch);
      if (poolIds.length === 0) break;
    }

    localStorage.setItem(key, JSON.stringify(queue));
    return queue;
  }

  drawQuestions(poolIds, key, count) {
    if (!poolIds.length) return [];
    let queue = this.ensureQueue(poolIds, key, count);
    const selected = queue.slice(0, count);
    queue = queue.slice(count);
    localStorage.setItem(key, JSON.stringify(queue));
    const map = new Map(this.questions.map(q => [q.id, q]));
    return selected.map(id => map.get(id)).filter(Boolean);
  }

  prepareExamQuestions(rawQuestions) {
    return this.shuffle(rawQuestions).map(q => {
      const paired = q.options.map((opt, idx) => ({ opt, idx }));
      const shuffled = this.shuffle(paired);
      const newOptions = shuffled.map(x => x.opt);
      const newCorrectSet = shuffled
        .map((x, newIdx) => q.correctSet.includes(x.idx) ? newIdx : null)
        .filter(v => v !== null);
      return {
        ...q,
        options: newOptions,
        correctSet: newCorrectSet,
        multiple: q.multiple || q.correctSet.length > 1
      };
    });
  }

